#!/usr/bin/env python3
"""Reads the running cluster with kubectl and writes data.js for the cluster map page. Run: make cluster-map."""

import json
import re
import subprocess  # nosec B404 - runs kubectl and docker with fixed arguments, never a shell
import sys
from datetime import datetime, timezone
from pathlib import Path

from model import ClusterFacts, Reference, build_model

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
OUTPUT = HERE / "data.js"
GRAFANA_VARS = REPO_ROOT / "monitoring/grafana/ansible/vars.yaml"
RESOURCES = [
    "nodes",
    "pods",
    "services",
    "ingresses",
    "serviceaccounts",
    "secrets",
    "configmaps",
    "persistentvolumeclaims",
    "persistentvolumes",
    "networkpolicies",
    "roles",
    "rolebindings",
    "clusterroles",
    "clusterrolebindings",
]


def run(command: list[str]) -> str:
    """Run a command and return its stdout; raises CalledProcessError if it fails."""
    return subprocess.run(command, capture_output=True, text=True, check=True).stdout  # nosec B603 B607


def docker_subnet(network: str = "kind") -> str:
    """Return the IPv4 subnet of kind's Docker network, or '' if Docker can't tell."""
    try:
        output = run(["docker", "network", "inspect", network, "--format", "{{range .IPAM.Config}}{{.Subnet}} {{end}}"])
    except (OSError, subprocess.CalledProcessError):
        return ""
    return next((subnet for subnet in output.split() if "." in subnet), "")


def grafana_references() -> list[Reference]:
    """Return Grafana's Prometheus datasource URL, which Ansible sets outside Kubernetes."""
    match = re.search(r'^prometheus_url:\s*"?([^"\s]+)', GRAFANA_VARS.read_text(), re.MULTILINE)
    return [Reference(app="grafana", value=match.group(1))] if match else []


def read_cluster() -> tuple[list[dict], ClusterFacts]:
    """Fetch every object the map needs plus version and context; raises if kubectl fails."""
    items = json.loads(run(["kubectl", "get", ",".join(RESOURCES), "--all-namespaces", "-o", "json"]))["items"]
    facts = ClusterFacts(
        context=run(["kubectl", "config", "current-context"]).strip(),
        version=json.loads(run(["kubectl", "version", "-o", "json"]))["serverVersion"]["gitVersion"],
        node_network=docker_subnet(),
        generated_at=datetime.now(timezone.utc).isoformat(timespec="seconds"),
    )
    return items, facts


def main() -> int:
    """Write data.js from the current kubectl context; return the process exit code."""
    try:
        items, facts = read_cluster()
    except FileNotFoundError:
        print("kubectl not found on PATH", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as error:
        print(f"kubectl failed: {error.stderr.strip()}\nIs the cluster running? ./recreate-cluster.sh", file=sys.stderr)
        return 1
    model = build_model(items, facts, grafana_references())
    OUTPUT.write_text(
        f"// Generated by cluster_map.py; do not edit.\nwindow.CLUSTER_MAP = {json.dumps(model, indent=1)};\n"
    )
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} from context {facts.context} ({len(model['pods'])} pods)")
    print(f"Open {HERE / 'index.html'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
